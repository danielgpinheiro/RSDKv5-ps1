/*
 * Build-time trig tables for the RSDKv5 PS1 port (docs/ports/mania/32 phase 2.1; the Sonic CD lesson, docs/ports/sonic-cd/28 2.2).
 *
 * RSDKv5's CalculateTrigAngles (RSDKv5/RSDK/Core/Math.cpp) fills 15 sin/cos/tan/asin/acos tables and a 64 KB
 * atan table with 65,536 atan2 calls at boot: tens of seconds on the R3000A (no FPU, soft-float). This host
 * program runs the same loops (same types and expressions as on the PC) and prints the tables as C
 * initializers; Math.cpp includes them on PS1 instead of computing them.
 * Usage: gen_trig > build/gen/trig_tables.inc   (the Makefile does this)
 */
#include <math.h>
#include <stdint.h>
#include <stdio.h>

#define RSDK_PI (3.1415927f)

static int32_t sin1024[0x400], cos1024[0x400], tan1024[0x400], asin1024[0x400], acos1024[0x400];
static int32_t sin512[0x200], cos512[0x200], tan512[0x200], asin512[0x200], acos512[0x200];
static int32_t sin256[0x100], cos256[0x100], tan256[0x100], asin256[0x100], acos256[0x100];
static uint8_t arcTan256[0x100 * 0x100];

static void dump(const char *name, const int32_t *v, int n)
{
    printf("int32 RSDK::%s[0x%x] = {", name, n);
    for (int i = 0; i < n; ++i) printf("%s%d", i == 0 ? "\n    " : i % 16 ? ", " : ",\n    ", v[i]);
    printf("\n};\n");
}

int main(void)
{
    // Math.cpp CalculateTrigAngles, verbatim apart from the table names.
    for (int32_t i = 0; i < 0x400; ++i) {
        sin1024[i]  = (int32_t)(sinf((i / 512.f) * RSDK_PI) * 1024.f);
        cos1024[i]  = (int32_t)(cosf((i / 512.f) * RSDK_PI) * 1024.f);
        tan1024[i]  = (int32_t)(tanf((i / 512.f) * RSDK_PI) * 1024.f);
        asin1024[i] = (int32_t)((asinf(i / 1023.f) * 512.f) / RSDK_PI);
        acos1024[i] = (int32_t)((acosf(i / 1023.f) * 512.f) / RSDK_PI);
    }
    cos1024[0x000] = 0x400; cos1024[0x100] = 0; cos1024[0x200] = -0x400; cos1024[0x300] = 0;
    sin1024[0x000] = 0; sin1024[0x100] = 0x400; sin1024[0x200] = 0; sin1024[0x300] = -0x400;

    for (int32_t i = 0; i < 0x200; ++i) {
        sin512[i]  = (int32_t)(sinf((i / 256.f) * RSDK_PI) * 512.f);
        cos512[i]  = (int32_t)(cosf((i / 256.f) * RSDK_PI) * 512.f);
        tan512[i]  = (int32_t)(tanf((i / 256.f) * RSDK_PI) * 512.f);
        asin512[i] = (int32_t)((asinf(i / 511.f) * 256.f) / RSDK_PI);
        acos512[i] = (int32_t)((acosf(i / 511.f) * 256.f) / RSDK_PI);
    }
    cos512[0x00] = 0x200; cos512[0x80] = 0; cos512[0x100] = -0x200; cos512[0x180] = 0;
    sin512[0x00] = 0; sin512[0x80] = 0x200; sin512[0x100] = 0; sin512[0x180] = -0x200;

    for (int32_t i = 0; i < 0x100; i++) {
        sin256[i]  = (int32_t)((sin512[i * 2] >> 1));
        cos256[i]  = (int32_t)((cos512[i * 2] >> 1));
        tan256[i]  = (int32_t)((tan512[i * 2] >> 1));
        asin256[i] = (int32_t)((asinf(i / 255.f) * 128.f) / RSDK_PI);
        acos256[i] = (int32_t)((acosf(i / 255.f) * 128.f) / RSDK_PI);
    }

    for (int32_t y = 0; y < 0x100; ++y) {
        uint8_t *arcTan = &arcTan256[y];
        for (int32_t x = 0; x < 0x100; ++x) {
            *arcTan = (int32_t)(float)((float)atan2((float)y, x) * 40.743664f);
            arcTan += 0x100;
        }
    }

    printf("// generated by tools/trig/gen_trig.c: RSDKv5 CalculateTrigAngles tables, computed on the host\n");
    dump("sin1024LookupTable", sin1024, 0x400); dump("cos1024LookupTable", cos1024, 0x400);
    // docs/ports/mania/32 7b.7: no tan / asin / acos tables (21 KB of RAM): neither the game nor the engine reads them (Math.hpp)
    dump("sin512LookupTable", sin512, 0x200); dump("cos512LookupTable", cos512, 0x200);
    dump("sin256LookupTable", sin256, 0x100); dump("cos256LookupTable", cos256, 0x100);
    (void)tan1024; (void)asin1024; (void)acos1024; (void)tan512; (void)asin512; (void)acos512;
    (void)tan256; (void)asin256; (void)acos256;
    // PS1 (docs/ports/mania/32 2.3j): the 64 KB arcTan256 table as 63 ratio thresholds. For x > 0 the value rises with y / x; for each
    // v = 1..63, the smallest y / x (a (y, x) pair) whose value is >= v. ArcTanLookup counts the thresholds y / x reaches
    // (x = 0: 64 unless y = 0). Checked here against every entry; a mismatch stops the build.
    int thrY[64], thrX[64];
    for (int v = 1; v < 64; ++v) {
        thrY[v] = -1;
        for (int x = 1; x < 0x100; ++x)
            for (int y = 0; y < 0x100; ++y)
                if (arcTan256[(x << 8) + y] >= v && (thrY[v] < 0 || y * thrX[v] < thrY[v] * x)) {
                    thrY[v] = y;
                    thrX[v] = x;
                }
        if (thrY[v] < 0) {
            fprintf(stderr, "gen_trig: no threshold for %d\n", v);
            return 1;
        }
    }
    for (int x = 0; x < 0x100; ++x) {
        for (int y = 0; y < 0x100; ++y) {
            int value = 0;
            if (!x)
                value = y ? 64 : 0;
            else
                for (int v = 1; v < 64; ++v) value += y * thrX[v] >= thrY[v] * x;
            if (value != arcTan256[(x << 8) + y]) {
                fprintf(stderr, "gen_trig: threshold arctan (%d, %d) = %d, table %d\n", x, y, value, arcTan256[(x << 8) + y]);
                return 1;
            }
        }
    }
    printf("const uint8 RSDK::ps1ArcTanThreshold[64][2] = {\n    { 0, 0 }");
    for (int v = 1; v < 64; ++v) printf(",%s{ %d, %d }", v % 8 ? " " : "\n    ", thrY[v], thrX[v]);
    printf("\n};\n");
    return 0;
}
