#!/usr/bin/env python3
"""The debug overlay's font (docs/ports/mania/32 "Debug overlay", ps1/debug_overlay.cpp): 5x7 glyphs as flat rectangles.

The overlay draws text with opaque GP0 60h rectangles only (no font texture, no VRAM). Each glyph below is a 5x7 bitmap,
one byte a row, bit 4 the left column (ps1/version_stamp.cpp's style). For each glyph this picks the smaller of two exact
minimum covers (rectangles may overlap: one colour, opaque):
  - ink: the lit cells' horizontal runs merged into rectangles;
  - holes: one text-coloured block over the glyph's bounding box, then box-coloured rectangles over the unlit cells
    inside it (the overlay's box is opaque and the holes take its colour, so they vanish into it).
A tie keeps the ink cover.

Writes ps1/debug_overlay_font.inc (committed; rerun after changing a glyph). debug_overlay.cpp checks the table at
compile time: each glyph's rectangles, drawn in order, must give its bitmap again.
Usage: tools/overlay_font.py [OUT]
"""
import itertools
import os
import sys

# Blocky shapes: the fewest rectangles that still read at 5x7 (S is drawn like 5)
GLYPHS = [
    ('0', [0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F]),
    ('1', [0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E]),
    ('2', [0x1F, 0x01, 0x01, 0x1F, 0x10, 0x10, 0x1F]),
    ('3', [0x1F, 0x01, 0x01, 0x1F, 0x01, 0x01, 0x1F]),
    ('4', [0x11, 0x11, 0x11, 0x1F, 0x01, 0x01, 0x01]),
    ('5', [0x1F, 0x10, 0x10, 0x1F, 0x01, 0x01, 0x1F]),
    ('6', [0x1F, 0x10, 0x10, 0x1F, 0x11, 0x11, 0x1F]),
    ('7', [0x1F, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01]),
    ('8', [0x1F, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x1F]),
    ('9', [0x1F, 0x11, 0x11, 0x1F, 0x01, 0x01, 0x1F]),
    ('F', [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10]),
    ('P', [0x1F, 0x11, 0x11, 0x1F, 0x10, 0x10, 0x10]),
    ('S', [0x1F, 0x10, 0x10, 0x1F, 0x01, 0x01, 0x1F]),
    ('R', [0x1F, 0x11, 0x11, 0x1F, 0x12, 0x11, 0x11]),
    ('A', [0x1F, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11]),
    ('M', [0x1F, 0x15, 0x15, 0x15, 0x15, 0x15, 0x15]),
    ('V', [0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04]),
    ('U', [0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F]),
    ('K', [0x12, 0x12, 0x14, 0x18, 0x14, 0x12, 0x12]),
    ('/', [0x01, 0x01, 0x02, 0x04, 0x08, 0x10, 0x10]),
    ('%', [0x19, 0x19, 0x02, 0x04, 0x08, 0x13, 0x13]),
    (':', [0x00, 0x0C, 0x0C, 0x00, 0x0C, 0x0C, 0x00]),
    (' ', [0x00] * 7),
]
W, H = 5, 7


def cells(rows):
    return {(x, y) for y, r in enumerate(rows) for x in range(W) if r >> (W - 1 - x) & 1}


def min_cover(target):
    """The first (in a fixed order) smallest set of rectangles inside `target` whose union is `target`."""
    if not target:
        return []
    rects = []
    for y0 in range(H):
        for x0 in range(W):
            for y1 in range(y0, H):
                for x1 in range(x0, W):
                    c = frozenset((x, y) for x in range(x0, x1 + 1) for y in range(y0, y1 + 1))
                    if c <= target:
                        rects.append(((x0, y0, x1 - x0 + 1, y1 - y0 + 1), c))
    rects = [r for r in rects if not any(r[1] < o[1] for o in rects)]  # the maximal ones
    for k in range(1, len(rects) + 1):
        for combo in itertools.combinations(rects, k):
            if frozenset().union(*(c for _, c in combo)) == target:
                return [r for r, _ in combo]
    raise AssertionError('no cover')


def glyph_rects(rows):
    """[(x, y, w, h, hole)]: the text-coloured rectangles first, then the box-coloured holes."""
    lit = cells(rows)
    if not lit:
        return []
    ink = [(x, y, w, h, 0) for x, y, w, h in min_cover(lit)]
    xs, ys = [x for x, _ in lit], [y for _, y in lit]
    box = {(x, y) for x in range(min(xs), max(xs) + 1) for y in range(min(ys), max(ys) + 1)}
    if box == lit:
        return ink
    holes = [(min(xs), min(ys), max(xs) - min(xs) + 1, max(ys) - min(ys) + 1, 0)] + \
            [(x, y, w, h, 1) for x, y, w, h in min_cover(box - lit)]
    return holes if len(holes) < len(ink) else ink


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '..', 'ps1', 'debug_overlay_font.inc')
    starts, words, notes = [], [], []
    for ch, rows in GLYPHS:
        starts.append(len(words))
        rs = glyph_rects(rows)
        words += [x | y << 3 | (w - 1) << 6 | (h - 1) << 9 | hole << 12 for x, y, w, h, hole in rs]
        notes.append(' '.join('%s%d,%d %dx%d' % ('hole ' if hole else '', x, y, w, h) for x, y, w, h, hole in rs))
    starts.append(len(words))
    with open(out, 'w') as f:
        f.write("// Generated by tools/overlay_font.py (rerun it; don't edit): the debug overlay's 5x7 font as rectangles.\n")
        f.write('// A rectangle is x | y << 3 | (w - 1) << 6 | (h - 1) << 9 | hole << 12; holes are drawn in the box colour, after\n')
        f.write("// the glyph's text-coloured rectangles. Bitmaps: one byte a row, bit 4 the left column (the compile-time check).\n")
        f.write('constexpr char kDbgGlyphChars[] = "%s";\n' % ''.join(c for c, _ in GLYPHS))
        f.write('constexpr int kDbgGlyphCount = %d;\n' % len(GLYPHS))
        f.write('constexpr uint8_t kDbgGlyphBits[%d][7] = {\n' % len(GLYPHS))
        for ch, rows in GLYPHS:
            f.write("    { %s }, // '%s'\n" % (', '.join('0x%02X' % r for r in rows), ch))
        f.write('};\n')
        f.write('constexpr uint8_t kDbgGlyphStart[%d] = { %s };\n' % (len(starts), ', '.join(str(s) for s in starts)))
        f.write('constexpr uint16_t kDbgGlyphRects[%d] = {\n' % len(words))
        for k, (ch, _) in enumerate(GLYPHS):
            ws = words[starts[k]:starts[k + 1]]
            if ws:
                f.write("    %s, // '%s' %d: %s\n" % (', '.join('0x%04X' % w for w in ws), ch, len(ws), notes[k]))
        f.write('};\n')
    print('%s: %d glyphs, %d rectangles' % (out, len(GLYPHS), len(words)))


if __name__ == '__main__':
    main()
