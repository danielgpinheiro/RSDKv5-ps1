#!/usr/bin/env python3
"""Stubs for the game symbols the linked objects reference but this build does not link (docs/32 phase 2.1).

The PS1 build links only some of Mania's 610 objects (tools/gen_objects.py; per zone in 2.4). Linked code still
names the others: object static pointers (`Current`, `Button`, ...) and functions (state functions compared by
address, helpers of other zones). This writes one C file with
  - a NULL definition for every unlinked object pointer: exactly the PC's value for an object that is not in the
    loaded scene (Object.cpp clears it, Scene.cpp only allocates the scene's objects);
  - a distinct stub for every unlinked function: it counts the call in g_ps1UnlinkedCalls and remembers which one
    (g_ps1UnlinkedLast = index into the comment table below) so GDB shows any stub that is actually reached.
Usage: gen_stubs.py OUT.c OBJ... (the Makefile passes every object of the link)
"""
import os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..'))
NM = 'mipsel-none-elf-nm'


def nm(args):
    return subprocess.run([NM] + args, capture_output=True, text=True, check=True).stdout.splitlines()


def main():
    out, objs = sys.argv[1], sys.argv[2:]
    defined, undefined = set(), set()
    for line in nm(['--defined-only', '-g'] + objs + [os.path.join(REPO, '..', 'nugget', 'psyqo', 'libpsyqo.a')]):
        parts = line.split()
        if len(parts) == 3:
            defined.add(parts[2])
    game = [o for o in objs if o.startswith('SonicMania/')]
    for line in (nm(['-u'] + game) if game else []):  # no game objects (make PLATFORM_TEST=1): no stubs
        parts = line.split()
        if len(parts) == 2 and parts[0] == 'U':
            undefined.add(parts[1])
    classes = set()
    for root, _, files in os.walk(os.path.join(REPO, 'SonicMania', 'Objects')):
        classes.update(f[:-2] for f in files if f.endswith('.c') and f != 'All.c')
    missing = sorted(u for u in undefined - defined if not u.startswith('_'))
    data = [m for m in missing if m in classes]
    funcs = [m for m in missing if m not in classes]
    with open(out, 'w') as f:
        f.write('// generated by tools/gen_stubs.py: %d unlinked object pointers, %d unlinked functions\n' % (len(data), len(funcs)))
        f.write('volatile unsigned g_ps1UnlinkedCalls = 0; // unlinked functions called (GDB)\n')
        f.write('volatile unsigned g_ps1UnlinkedLast  = 0; // 1 + index of the last one (list below)\n')
        f.write('volatile unsigned g_ps1UnlinkedSeen[8];   // the first 8 distinct ones reached (1 + index)\n')
        f.write('// A stub returns a zeroed scratch block: a caller that uses the result as a pointer writes here, not into\n')
        f.write('// the BIOS kernel at address 0 (what a NULL result would do). A reached stub is a missing object to link.\n')
        f.write('static unsigned s_scratch[1024];\n')
        f.write('static void *hit(unsigned id) {\n')
        f.write('    g_ps1UnlinkedCalls++; g_ps1UnlinkedLast = id;\n')
        f.write('    for (int i = 0; i < 8; i++) { if (g_ps1UnlinkedSeen[i] == id) break; if (!g_ps1UnlinkedSeen[i]) { g_ps1UnlinkedSeen[i] = id; break; } }\n')
        f.write('    for (int i = 0; i < 1024; i++) s_scratch[i] = 0;\n')
        f.write('    return s_scratch;\n}\n\n')
        for d in data:
            f.write('void *%s = 0;\n' % d)
        f.write('\n')
        for i, fn in enumerate(funcs):
            f.write('void *%s(void) { return hit(%d); }\n' % (fn, i + 1))
    print('gen_stubs: %d unlinked object pointers, %d unlinked functions -> %s' % (len(data), len(funcs), out))


if __name__ == '__main__':
    main()
