#!/usr/bin/env python3
"""Which Mania objects the PS1 build links (phase 2; docs/32): the GameConfig's global objects plus the
StageConfig objects of the chosen stage folders, resolved to their sources in SonicMania/Objects.
Writes:
  ps1/rsdk5_objects.inc   RSDK_REGISTER_OBJECT(X) lines: the PS1 version of Game.c's InitGameLogic list
  build/gen/game_srcs.txt the object sources, one per line (the Makefile reads it)
Objects a scene names that are not linked fall back to the engine's default object (counted at load).
Later (2.2): one such set per zone = one code overlay.
Usage: gen_objects.py [DATA_DIR] [--stages GHZ,Logos,Title] [--extra Name,Name]
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rsdk5_formats as F

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..'))


def main():
    a = sys.argv[1:]
    stages, extra = ['Logos', 'Title', 'GHZ'], []
    if '--stages' in a:
        i = a.index('--stages'); stages = a[i + 1].split(','); del a[i:i + 2]
    if '--extra' in a:
        i = a.index('--extra'); extra = a[i + 1].split(','); del a[i:i + 2]
    data = a[0] if a else os.path.join(REPO, '..', 'SonicMania_Extracted', 'Data')
    # Sources from the tree (SonicMania/Objects.cfg is stale for a few: Player lives in Global/, ...).
    srcs = {}
    for root, _, files in sorted(os.walk(os.path.join(REPO, 'SonicMania', 'Objects'))):
        for f in sorted(files):
            if f.endswith('.c') and f != 'All.c':
                srcs[f[:-2]] = os.path.relpath(os.path.join(root, f), REPO)
    g = F.read_gameconfig(os.path.join(data, 'Game', 'GameConfig.bin'))
    names = list(g['objects'])
    for st in stages:
        p = os.path.join(data, 'Stages', st, 'StageConfig.bin')
        if os.path.exists(p):
            for o in F.read_stageconfig(p)['objects']:
                if o not in names:
                    names.append(o)
    for o in extra:
        if o and o not in names:
            names.append(o)
    # Helpers/ (MathHelpers, BadnikHelpers, ...) are code every zone calls: always linked (resident). Only the ones a
    # config lists are registered: a class outside the scene lists never gets static vars on the PC either.
    helpers = [f[:-2] for f in sorted(os.listdir(os.path.join(REPO, 'SonicMania', 'Objects', 'Helpers')))
               if f.endswith('.c') and f[:-2] not in names]
    missing = [o for o in names if o not in srcs]
    names = [o for o in names if o in srcs]
    # Register in Game.c's order (the PC's objectClassList order).
    order = {}
    for line in open(os.path.join(REPO, 'SonicMania', 'Game.c')):
        line = line.strip()
        if line.startswith('RSDK_REGISTER_OBJECT(') and line.endswith(');'):
            order.setdefault(line[len('RSDK_REGISTER_OBJECT('):-2], len(order))
    names.sort(key=lambda o: order.get(o, len(order)))
    os.makedirs(os.path.join(REPO, 'build', 'gen'), exist_ok=True)
    with open(os.path.join(REPO, 'ps1', 'rsdk5_objects.inc'), 'w') as f:
        f.write('// generated by tools/gen_objects.py (stages %s): the objects this PS1 build links\n' % ','.join(stages))
        for o in names:
            f.write('RSDK_REGISTER_OBJECT(%s);\n' % o)
    with open(os.path.join(REPO, 'build', 'gen', 'game_srcs.txt'), 'w') as f:
        f.write('\n'.join(srcs[o] for o in names + helpers) + '\n')
    print('%d objects registered (%d global + %d stage) + %d helper sources for stages %s; %d names without a source: %s' % (
        len(names), len(g['objects']), len(names) - len(g['objects']), len(helpers), ','.join(stages), len(missing), ' '.join(missing[:8])))


if __name__ == '__main__':
    main()
